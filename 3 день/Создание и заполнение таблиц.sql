CREATE TABLE dbo.user_roles (
    role_id INT IDENTITY(1,1) PRIMARY KEY,
    role_name NVARCHAR(50) NOT NULL
);

CREATE TABLE dbo.users (
    user_id INT IDENTITY(1,1) PRIMARY KEY,
    role_id INT FOREIGN KEY REFERENCES dbo.user_roles(role_id),
    username NVARCHAR(50) NOT NULL,
    email NVARCHAR(100) NOT NULL,
    password_hash NVARCHAR(255) NOT NULL,
    created_at DATE NOT NULL
);

CREATE TABLE dbo.service_categories (
    category_id INT IDENTITY(1,1) PRIMARY KEY,
    category_name NVARCHAR(100) NOT NULL,
    description NVARCHAR(MAX)
);

CREATE TABLE dbo.services_instructions (
    instruction_id INT IDENTITY(1,1) PRIMARY KEY,
    category_id INT FOREIGN KEY REFERENCES dbo.service_categories(category_id),
    title NVARCHAR(255) NOT NULL,
    content_text NVARCHAR(MAX) NOT NULL,
    estimated_time_min INT,
    views_count INT DEFAULT 0
);

CREATE TABLE dbo.courses (
    course_id INT IDENTITY(1,1) PRIMARY KEY,
    course_name NVARCHAR(150) NOT NULL,
    description NVARCHAR(MAX),
    difficulty_level NVARCHAR(50)
);

CREATE TABLE dbo.video_courses (
    video_id INT IDENTITY(1,1) PRIMARY KEY,
    course_id INT FOREIGN KEY REFERENCES dbo.courses(course_id),
    video_title NVARCHAR(150) NOT NULL,
    duration_minutes INT NOT NULL
);

CREATE TABLE dbo.user_favorites (
    favorite_id INT IDENTITY(1,1) PRIMARY KEY,
    user_id INT FOREIGN KEY REFERENCES dbo.users(user_id),
    instruction_id INT FOREIGN KEY REFERENCES dbo.services_instructions(instruction_id),
    added_at DATE NOT NULL
);

CREATE TABLE dbo.support_tickets (
    ticket_id INT IDENTITY(1,1) PRIMARY KEY,
    user_id INT FOREIGN KEY REFERENCES dbo.users(user_id),
    subject NVARCHAR(255) NOT NULL,
    status NVARCHAR(50) DEFAULT 'New',
    created_at DATE NOT NULL
);

CREATE TABLE dbo.ticket_responses (
    response_id INT IDENTITY(1,1) PRIMARY KEY,
    ticket_id INT FOREIGN KEY REFERENCES dbo.support_tickets(ticket_id),
    admin_id INT FOREIGN KEY REFERENCES dbo.users(user_id),
    response_text NVARCHAR(MAX) NOT NULL,
    replied_at DATE NOT NULL
);
GO

